#!/bin/sh

# Скрипт для ежедневной проверки SSL сертификатов Let's Encrypt
# certbot обновляет сертификаты только если осталось менее 30 дней до истечения

# Проверяем и обновляем сертификаты при необходимости
certbot renew --quiet --no-self-upgrade

# Перезагружаем nginx только если сертификаты были обновлены
nginx -s reload
